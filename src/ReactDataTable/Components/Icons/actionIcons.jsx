export const ACTION_ICON_NAMES = Object.keys(ACTION_ICONS);

export function resolveActionIconName(name) {
  if (typeof name !== "string") return null;
  const key = name.trim().toLowerCase();
  if (!key) return null;
  if (ACTION_ICONS[key]) return key;
  const alias = ACTION_ICON_ALIASES[key];
  return alias && ACTION_ICONS[alias] ? alias : null;
}

export function ActionIcon({ name, className, ...props }) {
  const resolved = resolveActionIconName(name);
  if (!resolved) return null;
  return (
    <IconSvg className={className} {...props}>
      {ACTION_ICONS[resolved]}
    </IconSvg>
  );
}

export default ActionIcon;
